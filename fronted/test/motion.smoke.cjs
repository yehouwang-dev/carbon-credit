const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const baseURL = new URL(process.env.PORTFOLIO_URL || 'http://127.0.0.1:18082').origin;
const artifactDir = process.env.MOTION_SCREENSHOT_DIR || '/private/tmp';

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    const errors = [], external = [], failed = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { const url = new URL(request.url()); const isFontAsset = ['api.fontshare.com', 'cdn.fontshare.com'].includes(url.hostname) && ['stylesheet', 'font'].includes(request.resourceType()); if (url.origin !== baseURL && !isFontAsset) external.push(request.url()); });
    page.on('response', response => { if(response.status() >= 400) failed.push(`${response.status()} ${response.url()}`); });
    await page.goto(baseURL);
    await page.getByRole('heading', { name: 'Carbon credit records.' }).waitFor();
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.taste-hero h1')).opacity === '1');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await page.locator('.trace-sheet.is-hero').count(), 1);
    await page.locator('.trace-stage-selector button').first().click();
    assert.match(await page.locator('.trace-live-state').innerText(), /Issued\s+0 CC/);
    await page.locator('.trace-stage-selector button').last().click();
    assert.match(await page.locator('.trace-live-state').innerText(), /Balance\s+90 CC/);
    await page.screenshot({ path: path.join(artifactDir, 'carbon-studio-desktop.png') });
    const stage = page.locator('.taste-fragment-wrap').last();
    await stage.scrollIntoViewIfNeeded();
    await page.waitForFunction(() => document.querySelectorAll('.taste-fragment-wrap')[3].dataset.motion === 'visible');
    await page.getByRole('button', { name: /SEPARATE Governance/ }).click();
    assert.match(await page.locator('#architecture-detail').innerText(), /does not transfer application ownership/);
    await page.getByRole('button', { name: /ERC-20 Credits/ }).focus();
    await page.keyboard.press('Enter');
    assert.match(await page.locator('#architecture-detail').innerText(), /fungible balances/);
    await page.getByText('Open the complete architecture diagram').click();
    await page.waitForFunction(() => document.querySelector('.architecture-full img').naturalWidth > 0);
    await page.getByRole('button', { name: 'Pause motion', exact: true }).click();
    assert.equal(await page.locator('.portfolio').getAttribute('data-motion-paused'), 'true');
    assert.equal(await page.locator('.taste-hero-stage').evaluate(node => getComputedStyle(node).animationName), 'none');
    await page.getByRole('button', { name: 'Try the simulation', exact: true }).first().click();
    await page.getByText('Browser simulation with fictional data.', {exact:true}).click();
    await page.locator('.studio-disclaimer[open] .portfolio-warning').waitFor();
    await page.getByText('Browser simulation with fictional data.', {exact:true}).click();
    const stepButton = i => page.locator('.simulation-progress button').nth(i);
    assert.equal(await page.locator('.studio-step-panel').count(), 1, 'Only the current operation should be rendered');
    await stepButton(1).click();
    await page.getByRole('button', { name: '2. Issue simulated credits', exact: true }).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByRole('alert').evaluate(node => getComputedStyle(node).opacity), '1');
    await stepButton(0).click();
    assert.equal(await page.getByRole('alert').count(), 0, 'Step navigation clears obsolete feedback');
    await page.getByRole('button', { name: '1. Approve sample project', exact: true }).click();
    assert.equal(await stepButton(1).getAttribute('aria-current'), 'step');
    await page.getByRole('button', { name: '2. Issue simulated credits', exact: true }).click();
    await page.getByRole('button', { name: '3. Retire simulated credits', exact: true }).click();
    await page.getByRole('button', { name: '4. Find simulated record', exact: true }).click();
    const result = page.locator('.portfolio-query-result');
    assert.match(await result.innerText(), /10\s*CC/);
    assert.match(await result.innerText(), /SIM-ONLY-0001/);
    assert.equal(await result.evaluate(node => getComputedStyle(node).opacity), '1');
    assert.equal(await page.locator('.simulation-progress li[data-complete=true]').count(), 4);
    assert.equal(await page.locator('.portfolio-metrics strong .portfolio-sr-only').first().textContent(), '90');
    await page.screenshot({ path: path.join(artifactDir, 'carbon-studio-workspace.png'), fullPage: true });
    await page.getByPlaceholder('SIM-ONLY-0001').fill('SIM-ONLY-9999');
    assert.equal(await result.count(), 0);
    await page.getByRole('button', { name: '4. Find simulated record', exact: true }).click();
    assert.match(await result.innerText(), /No matching/);
    await page.locator('.portfolio-records button').first().click();
    assert.equal(await page.getByPlaceholder('SIM-ONLY-0001').inputValue(), 'SIM-ONLY-0001');
    await page.getByRole('button', { name: '4. Find simulated record', exact: true }).click();
    assert.match(await result.innerText(), /Found in this simulation/);
    // Navigating away and back retains this page session, then reset clears every dependent view.
    await page.getByRole('button', { name: 'Overview', exact: true }).click();
    await page.getByRole('button', { name: 'Try the simulation', exact: true }).first().click();
    assert.equal(await stepButton(3).getAttribute('aria-current'), 'step');
    assert.equal(await page.locator('.portfolio-metrics strong .portfolio-sr-only').first().textContent(), '90');
    await page.getByRole('button', { name: 'Reset simulation', exact: true }).click();
    assert.equal(await page.locator('.simulation-progress li[data-complete=true]').count(), 0);
    assert.equal(await stepButton(0).getAttribute('aria-current'), 'step');
    assert.equal(await page.locator('.portfolio-metrics strong .portfolio-sr-only').first().textContent(), '0');
    assert.equal(await page.locator('.portfolio-records button').count(), 0);
    await page.getByRole('button', { name: 'Resume motion', exact: true }).click();
    await page.getByRole('button', { name: '中文', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.ok(await page.locator('.portfolio-metrics strong>span[aria-hidden=true]').first().evaluate(node => parseFloat(getComputedStyle(node).fontSize)) >= 28);
    await page.screenshot({ path: path.join(artifactDir, 'carbon-studio-mobile-simulation.png'), fullPage: true });
    await page.getByRole('button', { name: '项目概览', exact: true }).click();
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.taste-hero h1')).opacity === '1');
    await page.screenshot({ path: path.join(artifactDir, 'carbon-studio-mobile-home.png') });
    for (const width of [320, 390, 768, 1024, 1440]) {
      await page.setViewportSize({width, height:900});
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `No horizontal overflow at ${width}px`);
    }
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button', { name: '区块链接口', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: '连接钱包', exact: true }).isDisabled(), true);
    assert.deepEqual(errors, []);
    assert.deepEqual(external, [], 'Only the declared Fontshare font assets may be external; no RPC requests');
    assert.deepEqual(failed, [], 'No failed assets');

    const reduced = await browser.newContext({ reducedMotion: 'reduce', viewport: { width: 390, height: 844 } });
    const rp = await reduced.newPage();
    await rp.goto(baseURL);
    assert.equal(await rp.getByRole('button', { name: 'Reduced motion', exact: true }).isDisabled(), true);
    assert.equal(await rp.locator('.taste-hero-stage').evaluate(node => getComputedStyle(node).animationName), 'none');
    assert.equal(await rp.locator('[data-motion=pending]').count(), 0);
    await rp.getByRole('button', { name: 'Try the simulation', exact: true }).first().click();
    await rp.locator('.simulation-progress button').nth(1).click();
    await rp.getByRole('button', { name: '2. Issue simulated credits', exact: true }).click();
    assert.equal(await rp.getByRole('alert').evaluate(node => getComputedStyle(node).opacity), '1');
    console.log('PASS: guided lifecycle, out-of-order error, session retention/reset, query miss/recovery, bilingual 320–1440px layout, architecture/keyboard, pause/reduced motion, no RPC or undeclared external assets/page errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
